"""data/catalog.csv -> data.js (window.ITEMS) for the static site.
Empty CSV cells become null (= shown as "unknown"/"not stated" on the site). Nothing is filled in.
Usage: python -I scripts/site_data.py      (run from repo root)
"""
import csv, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

# short keys keep data.js small (same idea as bike-finder)
KEYS = {"cat": "c", "type": "t", "seat_group": "g", "brand": "b", "model": "n", "subtitle": "d", "seller": "s",
        "seller_name": "sn", "price": "p", "price_reg": "pr", "in_stock": "st", "url": "u", "standard": "std",
        "isofix": "iso", "rotating": "rot", "age_from_m": "a0", "age_to_m": "a1", "height_min_cm": "h0",
        "height_max_cm": "h1", "weight_max_kg": "w1", "fold": "f", "import_status": "imp", "checked": "chk",
        "sponsored": "sp"}
NUM = {"price", "price_reg", "in_stock", "rotating", "age_from_m", "age_to_m", "height_min_cm", "height_max_cm",
       "weight_max_kg"}


def num(v):
    f = float(v)
    return int(f) if f == int(f) else f


def main():
    items = []
    with open(ROOT / "data" / "catalog.csv", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            o = {}
            for k, short in KEYS.items():
                v = (r.get(k) or "").strip()
                o[short] = None if v == "" else (num(v) if k in NUM else v)
            items.append(o)
    js = "// generated by scripts/site_data.py from data/catalog.csv - do not edit by hand\n"
    js += "window.ITEMS = " + json.dumps(items, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "data.js").write_text(js, encoding="utf-8")
    print(f"data.js: {len(items)} items")


if __name__ == "__main__":
    main()
